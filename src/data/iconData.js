// 전체 아이콘 생성 함수
function createAllIconsCategory(categoryData) {
    const allIcons = [];
    Object.keys(categoryData).forEach(category => {
        if (category !== '전체') {
            categoryData[category].forEach(icon => {
                if (!allIcons.includes(icon)) {
                    allIcons.push(icon);
                }
            });
        }
    });
    return allIcons;
}

